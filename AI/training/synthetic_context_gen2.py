def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "synthetic_context_2.csv"
    out = out if os.path.isabs(out) else os.path.join(DATA_DIR, out)
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)

    rows, seen = [], set()
    for label, pairs in DATA.items():
        for a_line, target in pairs:
            key = (a_line, target)
            if key in seen:
                continue
            seen.add(key)
            rows.append({
                "source": "synthetic2",
                "context": f"A: {a_line}",
                "text": target,
                "label": label,
                "note": "",
            })

    with open(out, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["source", "context", "text", "label", "note"])
        w.writeheader()
        w.writerows(rows)

    print(f"합성 {len(rows)}행 -> {out}")
    for l, c in collections.Counter(r["label"] for r in rows).most_common():
        print(f"  {l}: {c}")
    print("검수: context+text 읽고 label 이 맞나 확인. 틀리면 label 을 직접 수정(note 는 선택 메모).")
    print("[주의] 합성은 부족한 감정 보강용. 평가(test)는 반드시 실데이터로.")


if __name__ == "__main__":
    main()
