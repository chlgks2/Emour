def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "contrastive_context_2.csv"
    out = out if os.path.isabs(out) else os.path.join(DATA_DIR, out)
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)

    rows = []
    for target, ctxs in MINIMAL_PAIRS:
        for a_line, label in ctxs:
            rows.append({
                "source": "contrastive2", "context": f"A: {a_line}", "text": target,
                "label": label, "kind": "minimal_pair",
                "note": "감정단어 없는 target — 맥락으로만 판단",
            })
    for a_line, target, label, note in COUNTERFACTUAL:
        rows.append({
            "source": "contrastive2", "context": f"A: {a_line}", "text": target,
            "label": label, "kind": "counterfactual", "note": note,
        })

    with open(out, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["source", "context", "text", "label", "kind", "note"])
        w.writeheader()
        w.writerows(rows)

    mp = sum(len(c) for _, c in MINIMAL_PAIRS)
    print(f"대조쌍/반사실 #2 {len(rows)}행 -> {out}")
    print(f"  minimal_pair: {mp}행 / target {len(MINIMAL_PAIRS)}종")
    print(f"  counterfactual: {len(COUNTERFACTUAL)}행")
    print("  분포:", dict(collections.Counter(r["label"] for r in rows)))
    print("검수: label 미묘 — 3명이 나눠 '가장 신경 써서' 확인. 틀리면 label 직접 수정.")


if __name__ == "__main__":
    main()
