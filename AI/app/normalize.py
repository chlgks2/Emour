def normalize_label(raw: object) -> Optional[str]:
    # LLM 이 준 값을 15라벨 중 하나로. 못 바꾸면 None.
    # 처리 순서
    #     1) 문자열화 + 유니코드 정규화(NFC) — 한글 자모 분리 입력 방지
    #     2) 앞뒤 공백·문장부호 제거
    #     3) 그대로 유효하면 채택
    #     4) 별칭표에 있으면 치환
    #     5) 'A/B' 형태면 앞부분만 다시 시도
    #     6) 실패 → None (호출부가 폴백 처리)
    
    if raw is None:
        return None
    s = unicodedata.normalize("NFC", str(raw)).strip()
    s = re.sub(r"^[\"'`\s]+|[\"'`\s.!?~,·]+$", "", s)
    if not s:
        return None
    if s in _VALID:
        return s
    low = s.lower()
    if low in ALIASES:
        return ALIASES[low]
    if s in ALIASES:
        return ALIASES[s]
    if "/" in s:
        head = s.split("/")[0].strip()
        if head in _VALID:
            return head
        if head in ALIASES:
            return ALIASES[head]
    return None


